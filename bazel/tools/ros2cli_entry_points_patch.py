#!/usr/bin/env python3
"""Write bazel/patches/<pkg>_entry_points.patch: the RCR overlay of <pkg> lacks the egg-info entry_points.txt that
registers its ros2cli command, so `ros2 <command>` is missing. The patch adds one from setup.py's entry_points, the
way the ros2topic overlay does.

Usage: ros2cli_entry_points_patch.py <external dir of the pristine module, e.g. $(bazel info output_base)/external/ros2run+>
"""

import ast
import difflib
import os
import re
import sys


def main(src):
    pkg = os.path.basename(src.rstrip("/")).rstrip("+")
    version = re.search(r"<version>(.*?)</version>", open(os.path.join(src, "package.xml")).read()).group(1)
    setup = ast.parse(open(os.path.join(src, "setup.py")).read())
    groups = next(
        ast.literal_eval(kw.value) for node in ast.walk(setup) if isinstance(node, ast.Call)
        for kw in node.keywords if kw.arg == "entry_points")
    content = []
    for group, lines in groups.items():
        content += (["\"\","] if content else []) + ["\"[%s]\"," % group] + ["\"%s\"," % ln for ln in lines]

    before = open(os.path.join(src, "BUILD.bazel")).read()
    after = before
    load = 'load("@bazel_skylib//rules:write_file.bzl", "write_file")\n'
    assert load not in after
    after = after.replace('load("@launch_ros', load + 'load("@launch_ros', 1) if 'load("@launch_ros' in after else \
        re.sub(r'(load\("@rosdistro//ament:defs.bzl")', load.replace("\\", "\\\\") + r"\1", after, count=1)
    target = "write_file(\n    name = \"entry_points_txt\",\n    out = \"%s-%s.egg-info/entry_points.txt\",\n" \
        "    content = [\n%s    ],\n)\n\n" % (pkg, version, "".join("        %s\n" % c for c in content))
    lib = "py_library(\n    name = \"%s\"," % pkg
    assert after.count(lib) == 1, lib
    after = after.replace(lib, target + lib)
    start = after.index(lib)
    data = after.index('[":ament_index"]', start)
    after = after[:data] + '[\n        ":ament_index",\n        ":entry_points_txt",\n    ]' + after[data + 16:]
    patch = "".join(difflib.unified_diff(before.splitlines(True), after.splitlines(True), "a/BUILD.bazel", "b/BUILD.bazel"))
    out = os.path.join(os.path.dirname(__file__), "..", "patches", "%s_entry_points.patch" % pkg)
    open(out, "w").write(
        "Register the `ros2 %s` command: add the egg-info entry_points.txt from setup.py, as the ros2topic overlay does.\n"
        "Generated by bazel/tools/ros2cli_entry_points_patch.py.\n\n" % next(iter(groups["ros2cli.command"])).split()[0] + patch)


if __name__ == "__main__":
    for d in sys.argv[1:]:
        main(d)
